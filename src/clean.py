import os

import pandas as pd
customers = pd.read_csv("data/raw/customers.csv")
customers["city"] = customers['city'].str.strip().str.title()
print(customers['city'].value_counts())
gender_map = {"male" :"male","m":"male","female":"female","f":"female"}
customers['gender'] = customers['gender'].str.strip().str.lower().map(gender_map)
customers['gender'] = customers['gender'].fillna("unknown")
print(customers['gender'].value_counts())
customers.loc[(customers["age"] < 10) | (customers["age"] > 100), "age"] = float("nan")
print(customers["age"].isna().sum())
customers.groupby('city')['age'].mean()
city_median = (customers.groupby('city')['age'].transform('median'))
print(city_median.head())
customers['age'] =customers['age'].fillna(city_median)
print(customers['age'].isna().sum())
print(customers["age"].min(), customers["age"].max())
customers['signup_date'] = pd.to_datetime(customers['signup_date'])
print(customers.dtypes)
print(customers["city"].value_counts())
print(customers["gender"].value_counts())
print(customers["age"].isna().sum(), customers["age"].min(), customers["age"].max())
orders = pd.read_csv("data/raw/orders.csv")
orders["order_ts"] = pd.to_datetime(orders["order_ts"])
print(orders.dtypes)
orders = orders.drop_duplicates()
print(orders.shape)
orders = orders.sort_values("order_ts")
orders = orders.drop_duplicates(subset="order_id",keep="last")
print(orders.shape)
print(orders["status"].value_counts())
orders["order_amount"] = pd.to_numeric(orders["order_amount"],errors='coerce')
print(orders["order_amount"].isna().sum())
products= pd.read_csv("data/raw/products.csv")
orders = orders.merge(products[["product_id","price_inr"]],on="product_id",how="left")
print(orders.shape)
#round(price_inr × quantity × (1 − discount_pct / 100), 2)
cal = (orders["price_inr"] * orders["quantity"]*(1-orders["discount_pct"]/100)).round(2)
print(cal[orders["order_amount"].isna()].head(3))
orders["order_amount"] = orders["order_amount"].fillna(cal)
print(orders["order_amount"].isna().sum())
print(round(orders.loc[orders["status"] == "completed", "order_amount"].sum(), 2))
orders = orders.merge(products[["product_id","price_inr","category"]],on="product_id",how="left")
print(orders.shape)
print((orders["delivery_minutes"] < 0).sum())
orders.loc[orders["delivery_minutes"] < 0, "delivery_minutes"] = float("nan")
print(orders["delivery_minutes"].isna().sum())
completed = orders["status"] == "completed"
category_median = orders[completed].groupby("category")["delivery_minutes"].median()
print(category_median)
row_median = orders["category"].map(category_median)
print(row_median.head())
orders.loc[completed, "delivery_minutes"] = orders.loc[completed, "delivery_minutes"].fillna(row_median)
print(orders.loc[completed, "delivery_minutes"].isna().sum())
print(orders.loc[orders["status"] == "cancelled", "delivery_minutes"].isna().sum())
print(orders.shape)
print(orders["status"].value_counts())
print(orders.columns.tolist())
orders = orders[["order_id", "customer_id", "product_id", "quantity", "order_ts",
                 "status", "discount_pct", "order_amount", "delivery_minutes"]]
print(orders.shape)
os.makedirs("data/clean", exist_ok=True)
customers.to_csv("data/clean/customers.csv", index=False)
products.to_csv("data/clean/products.csv", index=False)
orders.to_csv("data/clean/orders.csv", index=False)
print(pd.read_csv("data/clean/customers.csv").shape)